# archv4: calibrate v2's displayed confidence. The shown confidence (the margin to the runner-up) barely tracks how often
# a label is right; how far his family's vote leads (famScore: the best family's score and its lead over the next) does.
# A logistic fit on the tune split (the user's 2K list, and the judged key at half weight) gives the chance his label's
# family is right; reliability bins and the calibration error on the held-out split, before and after.
# Usage: ARCHCMP_DIR=dir python3 calib.py [out.ts]   (dir: an archcmp dump)
import json, os, sys
import numpy as np
from sklearn.linear_model import LogisticRegression

D = os.environ['ARCHCMP_DIR']
R = [r for r in json.load(open(os.path.join(D, 'rows.json'))) if r['src'] != 'pick']

def feats(r):
    fs = sorted(r['v2']['famScore'].values(), reverse=True)
    return [fs[0], fs[0] - fs[1]]
def y(r):
    return float(r['v2']['cands'][0]['family'] in [t['family'] for t in r['target']])
def wt(r):
    return r['w'] * (0.5 if r['src'] == 'judged' else 1)

tune = [r for r in R if r['split'] == 'tune']
test = [r for r in R if r['split'] == 'test']
X = np.array([feats(r) for r in tune]); Y = np.array([y(r) for r in tune]); W = np.array([wt(r) for r in tune])
m = LogisticRegression(C=1.0).fit(X, Y, sample_weight=W)
a, (b, c) = float(m.intercept_[0]), [float(v) for v in m.coef_[0]]

def cal(r):
    f = feats(r)
    return 1 / (1 + np.exp(-(a + b * f[0] + c * f[1])))

BINS = [0, 0.2, 0.4, 0.5, 0.6, 0.7, 0.8, 1.01]
def table(rows, conf, name):
    p = np.array([conf(r) for r in rows]); yy = np.array([y(r) for r in rows]); w = np.array([wt(r) for r in rows])
    L = [f"  {name}:"]
    ece = 0
    for lo, hi in zip(BINS, BINS[1:]):
        k = (p >= lo) & (p < hi)
        if w[k].sum() == 0:
            continue
        acc = (w[k] * yy[k]).sum() / w[k].sum(); cm = (w[k] * p[k]).sum() / w[k].sum()
        ece += w[k].sum() / w.sum() * abs(acc - cm)
        L.append(f"    shown {lo:.1f}-{min(hi, 1):.1f}: n {k.sum():3d}, mean shown {100*cm:3.0f}%, family right {100*acc:3.0f}%")
    brier = (w * (p - yy) ** 2).sum() / w.sum()
    L.append(f"    calibration error {100*ece:.1f} points, Brier {brier:.3f}")
    return L, ece, brier

L = ['archv4 confidence calibration: what the shown confidence means = the chance his label\'s family is right (the user\'s',
     '2K list and the judged key at half weight). Fitted on the tune split (logistic on the best family score and its lead',
     f'over the next): conf = 1 / (1 + exp(-({a:.3f} + {b:.3f} x best + {c:.3f} x lead))). Held out:']
for name, f in [('before (margin to the runner-up)', lambda r: r['v2']['conf']), ('after (calibrated)', cal)]:
    t, _, _ = table(test, f, name)
    L += t
open(os.path.join(D, 'calib.txt'), 'w').write('\n'.join(L) + '\n')
print('\n'.join(L))
if len(sys.argv) > 1:
    open(sys.argv[1], 'w').write(f"""// GENERATED by tools/archetypes2k/archcmp/calib.py (from v2/archcmp.script.test.ts's data). Do not edit by hand.
// archv4: the shown confidence is the chance his label's family is right, from how far his family's vote leads (the best
// family's score and its lead over the next): a logistic fit on the tune split of the user's 2K list and the judged key.
export const CONF_CAL = {{ a: {a:.4f}, best: {b:.4f}, lead: {c:.4f} }};
""")
