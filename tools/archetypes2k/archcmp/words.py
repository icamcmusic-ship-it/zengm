# archv4: learn the descriptor words' bars from the user's 2K names. For each word, its rulebook test (its classes in the
# top X% at his position, plus its sub-rating, play-type and floor checks) is read at a grid of bars X
# (v2/archcmp.script.test.ts ARCHCMP_WORDS=1); the bar kept is the one whose yes/no best matches where 2K uses the word on
# the tune split of the user's 2K list (weighted F1), one bar per word, so the rule stays monotone and readable ("top X%").
# Usage: ARCHCMP_DIR=dir python3 words.py [out.ts]   (dir: the dump with ARCHCMP_WORDS=1; WORDS_MAX_SHIFT=n keeps each
# learned bar within n grid steps of the rulebook's). archv4: measured in the engine (a WORD_BARS table read by the
# descriptor tests, tests.ts testConcept's `bar`), it did not lift the held-out 2K names, so the rulebook's bars stay.
import json, os, re, sys
D = os.environ['ARCHCMP_DIR']
R = json.load(open(os.path.join(D, 'rows.json')))
HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, '../../../src/common/archetypes')
WORD_GRID = [0.05, 0.1, 0.15, 0.2, 0.25, 0.3, 0.35, 0.4, 0.45, 0.5, 0.55, 0.6, 0.65, 0.7]
CRAFTY_GRID = [-0.25, 0, 0.25, 0.5, 0.75, 1, 1.25, 1.5, 1.75, 2, 2.25, 2.5, 2.75, 3]

# descriptor key -> concept (grammar.ts), concept -> rulebook support (rulebook.data.ts)
gram = open(os.path.join(SRC, 'v2/grammar.ts')).read()
desc_block = gram[gram.index('export const DESCRIPTORS'):gram.index('export const ROLE_BY_KEY')]
CONCEPT = {}
for m in re.finditer(r'key: "(\w+)",[\s\S]*?concept: "(\w+)"', desc_block):
    CONCEPT[m.group(1)] = m.group(2)
rb = open(os.path.join(SRC, 'rulebook.data.ts')).read()
SUPPORT = {}
for m in re.finditer(r'\n\t(\w+): \{[\s\S]*?support: ([\d.]+)', rb[:rb.index('export const WORD_RULES')]):
    SUPPORT[m.group(1)] = float(m.group(2))
SUPPORT['crafty'] = 0.5
# (High-Flying's whole-word bar, top 25%, is the tighter one)
SUPPORT['air'] = min(SUPPORT.get('air', 1), 0.25)

def f1(rows, key, gi):
    tp = fp = fn = 0
    for r in rows:
        s = r['wt'][key]
        if s == '-':
            continue
        p = s[gi] == '1'
        y = key in r['target'][0]['descs']
        w = r['w']
        tp += w * (p and y); fp += w * (p and not y); fn += w * (y and not p)
    return 2 * tp / max(1e-9, 2 * tp + fp + fn), tp + fn

tune = [r for r in R if r['split'] == 'tune' and r['src'] in ('2k', '2kAllTime')]
test = [r for r in R if r['split'] == 'test' and r['src'] in ('2k', '2kAllTime')]
bars = {}
L = ['archv4 word bars: per descriptor, the bar (top X% at his position; Crafty: offensive feel z) that best matches 2K\'s',
     'use of the word on the tune split (weighted F1 of "passes the test" vs "2K\'s name has the word"); held-out F1 at the',
     'rulebook bar and at the learned one. Kept only where the tune F1 rises by 0.02 or more and 2K uses the word 5+ times.',
     f"{'word':14s} {'concept':11s} {'n tune':>6s} | rulebook bar  F1 tune/test | learned bar  F1 tune/test | kept"]
for key, concept in CONCEPT.items():
    grid = CRAFTY_GRID if concept == 'crafty' else WORD_GRID
    cur = SUPPORT.get(concept)
    if cur is None:
        continue
    ci = min(range(len(grid)), key=lambda i: abs(grid[i] - cur))
    scores = [f1(tune, key, i)[0] for i in range(len(grid))]
    n = f1(tune, key, 0)[1]
    # (ties: the stricter bar, i.e. the smaller top fraction / the higher Crafty bar)
    order = range(len(grid)) if concept != 'crafty' else reversed(range(len(grid)))
    # (WORDS_MAX_SHIFT: how far from the rulebook's bar a learned bar may go, in grid steps)
    ms = int(os.environ.get('WORDS_MAX_SHIFT', '99'))
    bi = max([i for i in order if abs(i - ci) <= ms], key=lambda i: scores[i])
    keep = n >= 5 and scores[bi] >= scores[ci] + 0.02
    if keep:
        bars[concept] = grid[bi]
    L.append(f"{key:14s} {concept:11s} {n:6.1f} | {grid[ci]:5.2f}  {100*scores[ci]:5.1f} / {100*f1(test, key, ci)[0]:5.1f}      | {grid[bi]:5.2f}  {100*scores[bi]:5.1f} / {100*f1(test, key, bi)[0]:5.1f}     | {'yes' if keep else 'no'}")
open(os.path.join(D, 'words.txt'), 'w').write('\n'.join(L) + '\n')
print('\n'.join(L))
print(json.dumps(bars))
if len(sys.argv) > 1:
    open(sys.argv[1], 'w').write(f"""// GENERATED by tools/archetypes2k/archcmp/words.py (from v2/archcmp.script.test.ts ARCHCMP_MODE=words). Do not edit by hand.
// archv4: the descriptor words' bars learned from the user's 2K names (tune split): for each word, the top fraction of
// players at his position (on its rulebook classes) from which 2K starts using it; for Crafty, the offensive-feel bar (z at
// his position). Words not listed keep the rulebook's bar.
export const WORD_BARS: Partial<Record<string, number>> = {json.dumps(bars)};
""")
