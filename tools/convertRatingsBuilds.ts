/*
 * Mechanical converter for the build table used by "Regenerate ratings".
 *
 * Usage: node tools/convertRatingsBuilds.ts /path/to/bbgmdraft
 *
 * Loads the BBGM Draft Class Workshop's own engine (js/ratings.js and its
 * dependencies) in Node, lets it run its load-time normalization, and writes the
 * RESULT (the 447 builds with their normalized offset vectors, per-build solver
 * scales, weight calibration and pot gaps, plus the class flavors) to
 *   src/common/ratingsBuilds/archetypes.data.ts
 *   src/common/ratingsBuilds/flavors.data.ts
 * so the table is never retyped by hand and the derived numbers are exactly the
 * ones the Workshop uses. Run oxfmt on the two generated files afterwards.
 */
import { createRequire } from "node:module";
import { writeFileSync } from "node:fs";
import path from "node:path";

const root = process.argv[2];
if (!root) {
	throw new Error("Usage: node tools/convertRatingsBuilds.ts <bbgmdraft dir>");
}

const require = createRequire(import.meta.url);
const g = globalThis as any;
g.window = g;
process.env.BBGM_STRICT_ROLES = "1";
for (const f of ["rng", "bbgm", "calibration", "config", "ratings"]) {
	require(path.join(root, "js", `${f}.js`));
}
const RB = g.RatingsBuilder;

const outDir = path.join(import.meta.dirname, "..", "src/common/ratingsBuilds");

const num = (x: number) => {
	// Exact: JSON round-trips doubles
	return JSON.stringify(x);
};

const obj = (o: Record<string, number>) =>
	`{${Object.entries(o)
		.map(([k, v]) => `${k}:${num(v)}`)
		.join(",")}}`;

const lines: string[] = [];
for (const a of RB.ARCHETYPES) {
	const parts = [
		`name:${JSON.stringify(a.name)}`,
		`min:${a.min}`,
		`max:${a.max}`,
		`w:${num(a.w)}`,
		`tags:${JSON.stringify(a.t ?? [])}`,
		`o:${obj(a.o)}`,
	];
	// Solver scales, only where they differ from the shared default
	const ns: Record<string, number> = {};
	for (const [k, v] of Object.entries(a.nscale as Record<string, number>)) {
		if (v !== RB.SHIFT_SCALE[k]) {
			ns[k] = v;
		}
	}
	if (Object.keys(ns).length > 0) {
		parts.push(`ns:${obj(ns)}`);
	}
	parts.push(
		`cal:${num(RB.WEIGHT_CAL[a.name] ?? 1)}`,
		`pot:${num(RB.POT_BY_ARCHETYPE[a.name] ?? 0)}`,
	);
	if (a.vol !== undefined) {
		parts.push(`vol:${num(a.vol)}`);
	}
	if (a.inj !== undefined) {
		parts.push(`inj:${num(a.inj)}`);
	}
	if (a.bio) {
		parts.push(`bio:${JSON.stringify(a.bio)}`);
	}
	lines.push(`\t{${parts.join(",")}},`);
}

writeFileSync(
	path.join(outDir, "archetypes.data.ts"),
	`// GENERATED by tools/convertRatingsBuilds.ts from the BBGM Draft Class Workshop's js/ratings.js. Do not edit by hand.
// ${RB.ARCHETYPES.length} builds ("archetypes"). \`o\` is the load-time-normalized (ovr-neutral) offset vector, \`ns\` the
// per-rating solver scales where they differ from SHIFT_SCALE, \`cal\` the height-gate weight calibration, \`pot\` the build's
// centered potential gap.

import type { Archetype } from "./types.ts";

export const ARCHETYPES: Archetype[] = [
${lines.join("\n")}
];
`,
);

const flavorLines = RB.CLASS_FLAVORS.map((f: any) => {
	return `\t{name:${JSON.stringify(f.name)},w:${num(f.w)},label:${JSON.stringify(f.label)},m:${obj(f.m)}},`;
});

writeFileSync(
	path.join(outDir, "flavors.data.ts"),
	`// GENERATED by tools/convertRatingsBuilds.ts from the BBGM Draft Class Workshop's js/ratings.js. Do not edit by hand.
// ${RB.CLASS_FLAVORS.length} class flavors. \`m\` multiplies the draw weight of every build carrying the tag.

import type { ClassFlavor } from "./types.ts";

export const CLASS_FLAVORS: ClassFlavor[] = [
${flavorLines.join("\n")}
];
`,
);

console.log(
	`Wrote ${RB.ARCHETYPES.length} builds and ${RB.CLASS_FLAVORS.length} flavors`,
);
