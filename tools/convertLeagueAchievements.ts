/*
 * Mechanical converter for the League achievements catalogue and engine.
 *
 * Usage: node tools/convertLeagueAchievements.ts /path/to/bbgm-league-explorer
 *
 * Loads the League Explorer's own docs/js/views/achievements-defs.js in Node (it
 * runs its load-time calibration, merging and description templating) and writes
 * the RESULT as data to
 *   src/common/leagueAchievements/defs.generated.ts
 * Value formatters (functions in the Explorer) are written as the name of one of
 * the formatters in src/common/leagueAchievements/defs.ts, matched on their source.
 *
 * The engine (docs/js/views/achievements-engine.js, ~560 metrics over the league's
 * raw data) is copied verbatim into
 *   src/common/leagueAchievements/engine.generated.ts
 * with only its UMD wrapper replaced by an ES module wrapper, so the numbers are
 * exactly the Explorer's. It is untyped JavaScript, so that file is excluded from
 * type checking and linting; src/common/leagueAchievements/engine.ts gives it types.
 *
 * Both files are excluded from oxfmt (.oxfmtrc.json), so they stay one row per tier.
 */
import { createRequire } from "node:module";
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const root = process.argv[2];
if (!root) {
	throw new Error(
		"Usage: node tools/convertLeagueAchievements.ts <bbgm-league-explorer dir>",
	);
}

const require = createRequire(import.meta.url);
const viewsDir = path.join(root, "docs", "js", "views");
const D = require(path.join(viewsDir, "achievements-defs.js"));

const outDir = path.join(
	import.meta.dirname,
	"..",
	"src/common/leagueAchievements",
);

// Formatter source -> name in defs.ts FORMATTERS
const FMT: Record<string, string> = {
	'(n) => "." + String(Math.round(n * 1000)).padStart(3, "0")': "rec",
	'(n) => "$" + (n / 1000).toLocaleString("en-US", { maximumFractionDigits: 1 }) + "M"':
		"money",
	"(n) => n.toFixed(1)": "f1",
	"(n) => n.toFixed(2)": "f2",
	'(n) => (n * 100).toFixed(1).replace(/\\.0$/, "") + "%"': "pct",
	'(n) => (n * 100).toFixed(1) + "%"': "pct1",
	'(n) => (n * 100).toFixed(0) + "%"': "pct0",
	'(n) => Math.floor(n).toLocaleString("en-US")': "floor",
	'(n) => Math.round(n).toLocaleString("en-US")': "round",
};

const RARITY_LETTER: Record<string, string> = {
	common: "c",
	rare: "r",
	legendary: "l",
	impossible: "i",
};

const fmtName = (f: unknown) => {
	if (typeof f !== "function") {
		return undefined;
	}
	const src = f.toString();
	const name = FMT[src];
	if (!name) {
		throw new Error(`Unknown value formatter: ${src}`);
	}
	return name;
};

const row = (d: any) => {
	const parts = [
		JSON.stringify(d.topic),
		JSON.stringify(d.metric),
		JSON.stringify(RARITY_LETTER[d.rarity]),
		JSON.stringify(d.t),
		JSON.stringify(d.name),
		JSON.stringify(d.desc),
		JSON.stringify(d.unit),
		d.low ? 1 : 0,
		JSON.stringify(d.kind),
		JSON.stringify(d.need),
		JSON.stringify(fmtName(d.fmtV) ?? null),
	];
	return `\t[${parts.join(", ")}],`;
};

const header = `// GENERATED by tools/convertLeagueAchievements.ts from the BBGM League Explorer's docs/js/views/achievements-defs.js. Do not edit by hand.
// ${D.defs.length} achievement tiers over ${new Set(D.defs.map((d: any) => d.metric)).size} metrics, after the Explorer's rarity calibration (CAL) and duplicate merging (MERGED).
// Rows: [topic, metric, rarity (c/r/l/i), threshold, name, description, unit, low (1: the threshold is a ceiling), kind, data needed, value formatter].
// RETIRED_ROWS are tiers calibrated out or merged into another tier: still computed (old ids resolve), never shown or counted.

import type { DefRow } from "./defs.ts";
`;

const out = [
	header,
	`export const TOPICS: [string, string][] = ${JSON.stringify(D.TOPICS)};`,
	"",
	"export const DEF_ROWS: DefRow[] = [",
	...D.defs.map(row),
	"];",
	"",
	"export const RETIRED_ROWS: DefRow[] = [",
	...D.retired.map(row),
	"];",
	"",
	`export const MERGED: Record<string, string> = ${JSON.stringify(D.MERGED)};`,
	"",
].join("\n");
writeFileSync(path.join(outDir, "defs.generated.ts"), out);

// The engine, verbatim
const src = readFileSync(path.join(viewsDir, "achievements-engine.js"), "utf8");
const START = "function (Defs) {";
const startIdx = src.indexOf(START);
const endIdx = src.lastIndexOf("});");
if (startIdx < 0 || endIdx < startIdx) {
	throw new Error("Unexpected engine wrapper");
}
const body = src.slice(startIdx + START.length, endIdx);
const engineOut = `// @ts-nocheck
/* eslint-disable */
// GENERATED by tools/convertLeagueAchievements.ts from the BBGM League Explorer's docs/js/views/achievements-engine.js. Do not edit by hand.
// The engine's own source, verbatim, with its UMD wrapper replaced by this module. It reads the league in the Explorer's data shape, which src/common/leagueAchievements/adapter.ts builds from BBGM's database. Typed by engine.ts.

import { Defs } from "./defs.ts";

const factory = function (Defs) {${body}};

export const rawEngine = factory(Defs);
`;
writeFileSync(path.join(outDir, "engine.generated.ts"), engineOut);

console.log(
	`Wrote ${D.defs.length} tiers (${D.retired.length} retired) and the engine (${body.split("\n").length} lines)`,
);
