const escape = (s: string) => s.replaceAll(/[.*+?^${}()|[\]\\]/g, "\\$&");
const STATE_REGEXES = STATE_NAMES.map(
	(state) => [state, new RegExp(`\\b${escape(state)}\\b`)] as const,
);

/**
 * The state a school is in, or undefined if it is not known.
 */
export const schoolState = (school: string): string | undefined => {
	const known = SCHOOL_STATE[school];
	if (known) {
		return known;
	}
	for (const [state, regex] of STATE_REGEXES) {
		if (regex.test(school)) {
			return state;
		}
	}
	return undefined;
};

/**
 * A player's home state from his birthplace ("Ohio, USA"), or undefined for a player from outside the US.
 */
export const homeState = (loc: string): string | undefined => {
	if (!loc.endsWith(", USA")) {
		return undefined;
	}
	const state = loc.slice(0, -5);
	return DIVISION_OF.has(state) ? state : undefined;
};

export const sameDivision = (a: string | undefined, b: string | undefined) =>
	a !== undefined &&
	b !== undefined &&
	DIVISION_OF.get(a) !== undefined &&
	DIVISION_OF.get(a) === DIVISION_OF.get(b);
