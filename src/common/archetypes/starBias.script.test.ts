// @ts-nocheck
// Regenerates starBias.data.ts (RUN_ARCHETYPE_STARBIAS=1): the concentration trim for stars. A good player's ratings are
// high almost everywhere (BBGM's real ratings above all), so a few builds would name most of a league's best players. The
// top 150 real players by overall of every season 2016-2025 (read as a real-players league reads them) are evened out with
// a penalty-only bias (STAR_BIAS_MIN..0) on any build above STAR_TARGET of them or STAR_SEASON_MAX of one season's; it applies in full from a level well above
// his position's average (score.ts starWeight). Run after the calibration (it reads the calibrated norms).
import { writeFileSync } from "node:fs";
import { isGenericBuild } from "./generic.ts";
import { test } from "vitest";
import { ARCHETYPES, defaultNorms, scoreAll } from "./classify.ts";
import { realData, realNorms, realPlayer } from "./real.testutil.ts";
import { STAR_BIAS } from "./starBias.data.ts";

// (arch15: 197 builds, not 341: a little more room per build)
const STAR_TARGET = 0.03;
const STAR_SEASON_MAX = 0.035;
const STAR_BIAS_MIN = -1.5;
const GENERIC_STAR_TARGET = 0.01;
const ARCH16_ONLY = true;
const REPICKED = new Set([
	"drive-and-rise",
	"blow-by-dual-finisher",
	"board-hunting-bucket-getter",
	"backline-lob-threat",
]);

test.skipIf(!process.env.RUN_ARCHETYPE_STARBIAS)(
	"write star bias",
	() => {
		const data = realData();
		const players = [];
		for (let season = 2016; season <= 2025; season++) {
			players.push(
				...data.d.ratings
					.filter((r) => r.season === season)
					.map((r) => realPlayer(data, r))
					.sort((a, b) => b.ovr - a.ovr)
					.slice(0, 150),
			);
		}
		// (arch15: real players' sub-ratings read against each other)
		const norms = realNorms(defaultNorms(false), false);
		// (arch15: on top of the trim so far: a merged profile keeps its own entry, its build's applies too, classify.ts)
		const bias: Record<string, number> = { ...STAR_BIAS };
		for (let iter = 0; iter < 40; iter++) {
			const counts: Record<string, number> = {};
			// (and per season: no build above STAR_SEASON_MAX of any one season's 150)
			const bySeason: Record<string, number> = {};
			for (const p of players) {
				const best = scoreAll(
					p.ratings,
					{ ...norms, starBias: bias },
					ARCHETYPES,
					p.pos,
					undefined,
					{ age: p.age, stats: p.stats },
				).scored[0]!.a.id;
				counts[best] = (counts[best] ?? 0) + 1;
				const k = `${best}:${p.season}`;
				bySeason[k] = (bySeason[k] ?? 0) + 1;
			}
			const seasonMax: Record<string, number> = {};
			for (const [k, n] of Object.entries(bySeason)) {
				const id = k.split(":")[0]!;
				seasonMax[id] = Math.max(seasonMax[id] ?? 0, n / 150);
			}
			for (const a of ARCHETYPES) {
				// (arch16: only the generic builds and the builds whose kept name was re-picked are trimmed again; every other
				// build keeps its arch15 trim, so the players moved off a generic build are not pushed on again)
				if (ARCH16_ONLY && !isGenericBuild(a) && !REPICKED.has(a.id)) {
					continue;
				}
				const share = (counts[a.id] ?? 0) / players.length;
				const top = seasonMax[a.id] ?? 0;
				// (arch16: a generic build at most GENERIC_STAR_TARGET, generic.ts)
				const target = isGenericBuild(a) ? GENERIC_STAR_TARGET : STAR_TARGET;
				const seasonMaxA = isGenericBuild(a) ? 0.015 : STAR_SEASON_MAX;
				const b =
					(bias[a.id] ?? 0) +
					(share > target ? 0.4 * Math.log(target / share) : 0) +
					(top > seasonMaxA ? 0.3 * Math.log(seasonMaxA / top) : 0);
				if (b < (bias[a.id] ?? 0)) {
					bias[a.id] = Math.max(STAR_BIAS_MIN, b);
				}
			}
		}
		const out = Object.fromEntries(
			Object.entries(bias)
				.filter(([, v]) => v <= -0.2)
				.sort()
				.map(([k, v]) => [k, Math.round(v * 100) / 100]),
		);
		writeFileSync(
			new URL("./starBias.data.ts", import.meta.url),
			`// GENERATED by starBias.script.test.ts from the top 150 real players of every season 2016-2025. Do not edit by hand.
export const STAR_BIAS: Record<string, number> = ${JSON.stringify(out, null, "\t")};
`,
		);
	},
	1800000,
);
