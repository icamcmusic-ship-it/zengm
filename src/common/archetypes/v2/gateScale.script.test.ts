// archreview: the reference scale of the absolute gates (gateScale.ts): the quantiles of each gate key among the players
// of new random leagues (new-league defaults, players on rosters and in free agency, as getLeagueNorms reads a league),
// pooled over a few seeds. Not part of the normal run:
//   RUN_GATE_SCALE=1 npx vitest --run --project basketball src/common/archetypes/v2/gateScale.script.test.ts
// (archcov: RUN_GATE_SCALE=groups writes only nounGroups.data.ts, each noun's values among guards, wings and bigs)
import "fake-indexeddb/auto";
// @ts-expect-error node types are not in the web tsconfig, but tests run in node
import { writeFileSync } from "node:fs";
import { test } from "vitest";
import { LEAGUE_DATABASE_VERSION, PLAYER } from "../../constants.ts";
import { defaultGameAttributes } from "../../defaultGameAttributes.ts";
import { makeSeededRandom } from "../../random.ts";
import { last } from "../../utils.ts";
import { idb } from "../../../worker/db/index.ts";
import { league } from "../../../worker/core/index.ts";
import { getDefaultSettings } from "../../../worker/views/newLeague.ts";
import { helpers } from "../../../worker/util/index.ts";
import { ratingsForArchetype } from "../../../worker/core/player/archetype.ts";
import { ratingQuantiles } from "./gateScale.ts";
import { nounGroupQuantiles } from "./nouns.ts";
import type { ArchetypeRatings } from "../types.ts";

const SEEDS = [1, 2, 3, 4];

test.skipIf(!(globalThis as any).process.env.RUN_GATE_SCALE)(
	"gate scale reference",
	async () => {
		const rows: { ratings: ArchetypeRatings; ovr?: number; pos?: string }[] =
			[];
		for (const seed of SEEDS) {
			Math.random = makeSeededRandom(seed);
			await league.createStream(
				{},
				{
					confs: last(defaultGameAttributes.confs).value,
					divs: last(defaultGameAttributes.divs).value,
					fromFile: {
						gameAttributes: undefined,
						hasRookieContracts: true,
						maxGid: undefined,
						startingSeason: undefined,
						teams: undefined,
						version: LEAGUE_DATABASE_VERSION,
					},
					getLeagueOptions: undefined,
					keptKeys: new Set(),
					lid: seed,
					name: `gate scale ${seed}`,
					setLeagueCreationStatus: () => {},
					settings: getDefaultSettings() as any,
					shuffleRosters: false,
					startingSeasonFromInput: "2025",
					teamsFromInput: helpers.addPopRank(helpers.getTeamsDefault()),
					tid: 0,
				},
			);
			await league.loadGameAttributes();
			const players = await idb.cache.players.indexGetAll("playersByTid", [
				PLAYER.FREE_AGENT,
				Infinity,
			]);
			for (const p of players) {
				const ratings = ratingsForArchetype(p);
				if (ratings) {
					rows.push({
						ratings,
						ovr: (p.ratings.at(-1) as any).ovr,
						pos: (p.ratings.at(-1) as any).pos,
					});
				}
			}
		}
		writeFileSync(
			new URL("./nounGroups.data.ts", import.meta.url),
			`// GENERATED by v2/gateScale.script.test.ts (RUN_GATE_SCALE=groups). Do not edit by hand.
// archcov: each noun's value (nouns.ts nounValue) among the guards, wings and bigs of ${SEEDS.length} new random leagues
// (${rows.length} players on rosters and in free agency)
import type { NounGroupQuantiles } from "./nouns.ts";

export const NOUN_GROUP_REF: NounGroupQuantiles = ${JSON.stringify(nounGroupQuantiles(rows))};
`,
		);
		if ((globalThis as any).process.env.RUN_GATE_SCALE === "groups") {
			return;
		}
		const q = ratingQuantiles(rows);
		writeFileSync(
			new URL("./gateScale.data.ts", import.meta.url),
			`// GENERATED by v2/gateScale.script.test.ts (RUN_GATE_SCALE=1). Do not edit by hand.
// ${rows.length} players of ${SEEDS.length} new random leagues (new-league defaults, on rosters and in free agency)
import type { RatingQuantiles } from "./gateScale.ts";

export const GATE_REF: RatingQuantiles = ${JSON.stringify(q)};
`,
		);
	},
	1_200_000,
);
