// @ts-nocheck
// arch15: share trim (RUN_ARCHETYPE_SHARETRIM=1, ARCH_EXPANDED=1 for the expanded tables). A build merged from several
// profiles (classify.ts SCORING_ARCHETYPES) collects the players of all of them, so a few builds grew past an even share. This
// keeps every match table and every other bias as it is and only trims the builds above a cap, by population: a random
// league (19-32), veterans (32-37) and draftable prospects (each profile of a build moves with it), a small additive step
// on the bias per round (floor TRIM_MIN). Writes norms.data.ts / normsExpanded.data.ts.
import { writeFileSync } from "node:fs";
import { isGenericBuild } from "./generic.ts";
import { test } from "vitest";
import {
	SCORING_ARCHETYPES,
	defaultNorms,
	scoreAll,
	ARCHETYPES,
} from "./classify.ts";
import { positionFor } from "./position.ts";
import { sampleLeague } from "./sample.testutil.ts";

const EXPANDED = Boolean(process.env.ARCH_EXPANDED);
const TRIM_MIN = -1.2;
const CAPS = { league: 0.027, vets: 0.06, pros: 0.055 };
// arch16: a generic build (generic.ts) at most this share of any population
const GENERIC_CAP = 0.015;

test.skipIf(!process.env.RUN_ARCHETYPE_SHARETRIM)(
	"share trim",
	async () => {
		const norms = structuredClone(defaultNorms(EXPANDED));
		const pops = {
			league: await sampleLeague(4000, "trim-league", 13, 38, EXPANDED),
			vets: await sampleLeague(1500, "trim-vets", 18, 38, EXPANDED, 13),
			pros: (await sampleLeague(1500, "trim-pros", 0, 40, EXPANDED)).map(
				(p) => ({ ...p, prospect: true }),
			),
		};
		for (const ps of Object.values(pops))
			for (const p of ps) p.pos = positionFor(p.ratings, true);
		const log = [];
		for (let iter = 0; iter < 12; iter++) {
			const over = {};
			for (const [k, ps] of Object.entries(pops)) {
				const counts = {};
				for (const p of ps) {
					const id = scoreAll(
						p.ratings,
						norms,
						ARCHETYPES,
						p.pos,
						undefined,
						p.prospect ? { prospect: true } : { age: p.age },
					).scored[0].a.id;
					counts[id] = (counts[id] ?? 0) + 1;
				}
				for (const [id, c] of Object.entries(counts)) {
					const share = c / ps.length;
					const cap = isGenericBuild({ id }) ? GENERIC_CAP : CAPS[k];
					if (share > cap)
						over[id] = Math.max(over[id] ?? 0, Math.log(share / cap));
				}
			}
			log.push(
				`round ${iter}: ${Object.entries(over)
					.map(([id, v]) => `${id} ${v.toFixed(2)}`)
					.join(", ")}`,
			);
			if (Object.keys(over).length === 0) break;
			for (const sa of SCORING_ARCHETYPES) {
				const id = sa.out ?? sa.id;
				if (over[id])
					norms.bias[sa.id] = Math.max(
						TRIM_MIN,
						Math.round(((norms.bias[sa.id] ?? 0) - 0.3 * over[id]) * 100) / 100,
					);
			}
		}
		const name = EXPANDED ? "DEFAULT_NORMS_EXPANDED" : "DEFAULT_NORMS";
		writeFileSync(
			new URL(
				EXPANDED ? "./normsExpanded.data.ts" : "./norms.data.ts",
				import.meta.url,
			),
			`// GENERATED by calibrate.script.test.ts${EXPANDED ? " with the Expanded Ratings setting on" : ""} (arch14 tables, arch15 new builds added, arch15/arch16 share trim: shareTrim.script.test.ts). Do not edit by hand.\nimport type { Norms } from "./types.ts";\n\nexport const ${name}: Norms = ${JSON.stringify(norms)};\n`,
		);
		writeFileSync(
			process.env.ARCH_TRIM_OUT ?? "/tmp/trim.txt",
			log.join("\n") + "\n",
		);
	},
	3600000,
);
