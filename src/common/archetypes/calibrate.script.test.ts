/* eslint-disable no-undef */
// @ts-nocheck
// Regenerates norms.data.ts (RUN_ARCHETYPE_CALIBRATION=1) or, with ARCH_EXPANDED=1 too, normsExpanded.data.ts: the same
// reference league generated with the Expanded Ratings setting on. Not part of the normal run.
import { writeFileSync } from "node:fs";
import { test } from "vitest";
import { ARCHETYPES, scoreAll } from "./classify.ts";
import { buildNorms } from "./match.ts";
import { buildBaseNorms } from "./norms.ts";
import { positionFor } from "./position.ts";
import { sampleLeague } from "./sample.testutil.ts";

const EXPANDED = Boolean(process.env.ARCH_EXPANDED);
const BIAS_MAX = 0.2;
// Overused archetypes may be trimmed a little harder than rare ones are pushed up
const BIAS_MIN = -0.45;

test.skipIf(!process.env.RUN_ARCHETYPE_CALIBRATION)(
	"write norms",
	async () => {
		// A whole league, 19 to 32 year olds
		const sample = await sampleLeague(8000, "norms-v2", 13, 38, EXPANDED);
		// Positions as the game shows them with Improved positions on (the default)
		for (const p of sample) {
			p.pos = positionFor(p.ratings, true);
		}
		const norms = buildNorms(sample, ARCHETYPES);
		// The bias is evened out over the league plus a draft class or two of raw prospects, as a league holds them
		const prospects = (
			await sampleLeague(1200, "norms-prospects", 0, 30, EXPANDED)
		).map((p) => ({ ...p, pos: positionFor(p.ratings, true), prospect: true }));
		// Draft prospects are read against prospect tables (raw 19-year-olds as draft classes hold them)
		const prospectBase = buildBaseNorms(
			(await sampleLeague(4000, "norms-prospects-read", 0, 0, EXPANDED)).map(
				(p) => ({ ...p, pos: positionFor(p.ratings, true) }),
			),
		);
		norms.prospect = {
			q: prospectBase.q,
			beta: prospectBase.beta,
			pq: prospectBase.pq,
		};
		const biasSample = [...sample, ...prospects];
		const round = (xs: number[]) =>
			xs.map((x) => Math.round(x * 10000) / 10000);
		// Nudge the shares toward even with small additive steps on the z score. Kept small (-0.45 <= bias <= 0.2): correctness, which the
		// position gate and the name floors decide, matters more than evenness, so the bias only trims builds that are far
		// off. Even shares within each group (guard, wing, forward, big), the group sizes as the ratings give them.
		const bias: Record<string, number> = {};
		for (const a of ARCHETYPES) {
			bias[a.id] = 0;
		}
		let target: Record<string, number> | undefined;
		for (let iter = 0; iter < (ARCHETYPES.length > 0 ? 25 : 0); iter++) {
			const counts: Record<string, number> = {};
			for (const p of biasSample) {
				const best = scoreAll(
					p.ratings,
					{ ...norms, bias },
					ARCHETYPES,
					p.pos,
					undefined,
					p.prospect ? { prospect: true } : { age: p.age },
				).scored[0]!.a.id;
				counts[best] = (counts[best] ?? 0) + 1;
			}
			if (!target) {
				target = {};
				const groupShare: Record<string, number> = {};
				const groupN: Record<string, number> = {};
				for (const a of ARCHETYPES) {
					groupShare[a.group] =
						(groupShare[a.group] ?? 0) +
						(counts[a.id] ?? 0) / biasSample.length;
					groupN[a.group] = (groupN[a.group] ?? 0) + 1;
				}
				for (const a of ARCHETYPES) {
					target[a.id] = groupShare[a.group]! / groupN[a.group]!;
				}
			}
			for (const a of ARCHETYPES) {
				const actual = Math.max(
					0.0004,
					(counts[a.id] ?? 0) / biasSample.length,
				);
				bias[a.id] = Math.min(
					BIAS_MAX,
					Math.max(
						BIAS_MIN,
						bias[a.id]! + 0.15 * Math.log(target[a.id]! / actual),
					),
				);
			}
		}
		norms.bias = Object.fromEntries(
			Object.entries(bias).map(([k, v]) => [k, Math.round(v * 100) / 100]),
		);
		const q = Object.fromEntries(
			Object.entries(norms.q).map(([k, v]) => [k, round(v)]),
		);
		const src = `// GENERATED by calibrate.script.test.ts from 8000 BBGM-generated players (developed random draft classes, 19 to 32) and 1200 draft prospects${EXPANDED ? ", with the Expanded Ratings setting on" : ""}. Do not edit by hand.
import type { Norms } from "./types.ts";

export const ${EXPANDED ? "DEFAULT_NORMS_EXPANDED" : "DEFAULT_NORMS"}: Norms = ${JSON.stringify({ q, beta: norms.beta, ovr: round(norms.ovr), match: norms.match, bias: norms.bias, pq: norms.pq, prospect: { q: Object.fromEntries(Object.entries(norms.prospect.q).map(([k, v]) => [k, round(v)])), beta: norms.prospect.beta, pq: norms.prospect.pq } })};
`;
		writeFileSync(
			new URL(
				EXPANDED ? "./normsExpanded.data.ts" : "./norms.data.ts",
				import.meta.url,
			),
			src,
		);
	},
	600000,
);
