// @ts-nocheck
// Regenerates seeds.data.ts: merges the 447 ratings builds into the archetypes. Not part of the normal run:
// RUN_ARCHETYPE_SEEDS=1
import { writeFileSync } from "node:fs";
import { test } from "vitest";
import { ARCHETYPES as BUILDS } from "../ratingsBuilds/archetypes.data.ts";
import { RATING_KEYS } from "../ratingsBuilds/solver.ts";
import { ARCHETYPES, scoreAll } from "./classify.ts";
import ovr from "../../worker/core/player/ovr.ts";
import { DEFAULT_NORMS } from "./norms.data.ts";
import { sampleLeague } from "./sample.testutil.ts";
import type { ArchetypeRatings, RatingKey } from "./types.ts";

const ovrOf = (r: any) => ovr(r);

test.skipIf(!process.env.RUN_ARCHETYPE_SEEDS)(
	"write seeds",
	async () => {
		const sample = await sampleLeague(4000, "seeds-v1");
		const KEYS = RATING_KEYS.filter((k) => k !== "hgt");
		const out: Record<string, any> = {};
		const ALL_DIMS = Object.keys(DEFAULT_NORMS.q);
		const dist = (x: any, y: any) => {
			let d = 0;
			for (const k of ALL_DIMS) d += ((x.w[k] ?? 0) - (y.w[k] ?? 0)) ** 2;
			return d;
		};
		// A uniform shift of every non-height rating that keeps the overall where it was: the solver restores the overall
		// too, so an offset is judged after it is neutralized
		const neutral = (
			r: ArchetypeRatings,
			o: Partial<Record<RatingKey, number>>,
			target: number,
		) => {
			const shifted = (c: number) => {
				const out2 = { ...r };
				for (const k of KEYS)
					out2[k] = Math.min(99, Math.max(1, r[k] + (o[k] ?? 0) + c));
				return out2;
			};
			let lo = -40,
				hi = 40;
			for (let i = 0; i < 7; i++) {
				const mid = (lo + hi) / 2;
				if (ovrOf(shifted(mid)) > target) hi = mid;
				else lo = mid;
			}
			return shifted((lo + hi) / 2);
		};
		const young = sample.filter((p) => p.age <= 23);
		for (const a of ARCHETYPES) {
			const [lo, hi] = a.hgt;
			const mid = (lo + hi) / 2;
			const inGate = (p: any) =>
				p.ratings.hgt >= lo && p.ratings.hgt <= hi && p.ovr >= 42;
			const near = (x: any, y: any) =>
				Math.abs(x.ratings.hgt - mid) - Math.abs(y.ratings.hgt - mid);
			const pool = [
				...young.filter(inGate).sort(near).slice(0, 14),
				...sample.filter(inGate).sort(near).slice(0, 14),
			];
			const comps = ARCHETYPES.filter(
				(c) => c.id !== a.id && c.hgt[1] >= lo && c.hgt[0] <= hi,
			)
				.sort((x, y) => dist(a, x) - dist(a, y))
				.slice(0, 16);
			const list = [a, ...comps];
			const o: Partial<Record<RatingKey, number>> = {};
			const objective = (cand: Partial<Record<RatingKey, number>>) => {
				let s = 0;
				for (const p of pool) {
					const r = neutral(p.ratings, cand, p.ovr);
					const sc = scoreAll(r, DEFAULT_NORMS, list).scored;
					const zt = sc.find((x) => x.a.id === a.id)!.z;
					const other = sc.find((x) => x.a.id !== a.id)!.z;
					s +=
						Math.max(-2.5, Math.min(0.9, zt - other)) + 0.1 * Math.min(2.6, zt);
				}
				let reg = 0;
				for (const k of KEYS) reg += (cand[k] ?? 0) ** 2;
				return s / pool.length - 0.0004 * reg;
			};
			let best = objective(o);
			for (const step of [8, 4, 2]) {
				for (let sweep = 0; sweep < 3; sweep++) {
					let moved = false;
					for (const k of KEYS) {
						for (const dir of [1, -1]) {
							const cand = {
								...o,
								[k]: Math.max(-30, Math.min(30, (o[k] ?? 0) + dir * step)),
							};
							const v = objective(cand);
							if (v > best + 1e-6) {
								best = v;
								o[k] = cand[k];
								moved = true;
							}
						}
					}
					if (!moved) break;
				}
			}
			out[a.id] = {
				o: Object.fromEntries(Object.entries(o).filter(([, v]) => v !== 0)),
				fit: Math.round(best * 100) / 100,
				n: pool.length,
			};
		}
		// Cluster the 447 builds onto the archetypes: nearest seed by cosine similarity among archetypes whose height gate overlaps
		const cos = (
			x: Partial<Record<RatingKey, number>>,
			y: Partial<Record<RatingKey, number>>,
		) => {
			let d = 0,
				nx = 0,
				ny = 0;
			for (const k of KEYS) {
				d += (x[k] ?? 0) * (y[k] ?? 0);
				nx += (x[k] ?? 0) ** 2;
				ny += (y[k] ?? 0) ** 2;
			}
			return d / (Math.sqrt(nx * ny) || 1);
		};
		for (const id of Object.keys(out)) out[id].builds = [];
		const used = new Set<string>();
		for (const b of BUILDS) {
			let bestId = "";
			let bestC = -2;
			for (const a of ARCHETYPES) {
				if (a.hgt[1] < b.min || a.hgt[0] > b.max) continue;
				const c = cos(b.o, out[a.id].o);
				if (c > bestC) {
					bestC = c;
					bestId = a.id;
				}
			}
			if (bestId) {
				out[bestId].builds.push(b.name);
				used.add(b.name);
			}
		}
		writeFileSync(
			new URL("./seeds.data.ts", import.meta.url),
			`// GENERATED by seeds.script.test.ts. An archetype's seed is the ovr-neutral rating offset vector that makes players inside
// its height gate fit its profile best (a regularized coordinate ascent on the profile's own match score). It is the target
// the ratings regenerator aims at (the solver then restores the exact overall). \`builds\` records how the 447 ratings builds
// (src/common/ratingsBuilds) cluster onto the archetypes: each build joins the archetype whose seed it is most similar to
// (cosine similarity of the offset vectors, among archetypes whose height gate overlaps the build's). Do not edit by hand.
import type { RatingKey } from "./types.ts";

export type Seed = {
	builds: string[];
	o: Partial<Record<RatingKey, number>>;
};

export const SEEDS: Record<string, Seed> = ${JSON.stringify(Object.fromEntries(Object.entries(out).map(([k, v]: any) => [k, { builds: v.builds, o: v.o }])), null, "\t")};
`,
		);
		const fits = Object.entries(out).map(([k, v]: any) => `${k} ${v.fit}`);
		const empty = Object.entries(out).filter(
			([, v]: any) => v.builds.length === 0,
		).length;
		writeFileSync(
			"/tmp/claude-0/seed-report.txt",
			`builds clustered ${used.size}/447, archetypes without builds ${empty}\n${fits.join("\n")}\n`,
		);
	},
	900000,
);
