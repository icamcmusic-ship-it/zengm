// @ts-nocheck
// Regenerates statNorms.data.ts (RUN_ARCHETYPE_STATNORMS=1): the stat references (by position bucket) the archetype reading
// uses for a player's box-score stats, from the real NBA seasons 2016-2025 (players with 500+ minutes, positions as the
// game shows them from that season's ratings). Real stats have no shot zones: a league's own games add those
// (getLeagueNorms). Not part of the normal run.
import { readFileSync, writeFileSync } from "node:fs";
import { test } from "vitest";
import { RATING_KEYS } from "../ratingsBuilds/solver.ts";
import { positionFor } from "./position.ts";
import { realSeasonStats } from "./real.testutil.ts";
import { buildStatNorms } from "./stats.ts";

test.skipIf(!process.env.RUN_ARCHETYPE_STATNORMS)(
	"write stat norms",
	() => {
		const d = JSON.parse(
			readFileSync(
				new URL(
					"../../../data/real-player-data.basketball.json",
					import.meta.url,
				),
				"utf8",
			),
		);
		const st = JSON.parse(
			readFileSync(
				new URL(
					"../../../data/real-player-stats.basketball.json",
					import.meta.url,
				),
				"utf8",
			),
		);
		const rows = [];
		for (const row of d.ratings) {
			if (row.season < 2016 || row.season > 2025) continue;
			const stats = realSeasonStats(st, row.slug, row.season);
			if (!stats) continue;
			const r = {};
			for (const k of RATING_KEYS) r[k] = row[k];
			// (the position as a real-players league shows it at the preseason: with the stats of the seasons before)
			const pos = positionFor({ ...r, season: row.season }, true, undefined, {
				stats: (st.stats[row.slug] ?? []).filter((x) => x.season < row.season),
			});
			rows.push({ stats, pos });
		}
		const norms = buildStatNorms(rows);
		writeFileSync(
			new URL("./statNorms.data.ts", import.meta.url),
			`// GENERATED by statNorms.script.test.ts from ${rows.filter((r) => r.stats.min >= 500).length} real NBA player-seasons 2016-2025 (500+ minutes). Do not edit by hand.
import type { StatNorms } from "./types.ts";

export const DEFAULT_STAT_NORMS: StatNorms = ${JSON.stringify(norms)};
`,
		);
	},
	600000,
);
