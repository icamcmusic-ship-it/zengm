// archrules: regenerates the rule answer key (RUN_ARCHETYPE_RULEKEY=1): every judged player (judged.data.ts, judgedSim.data.ts)
// read as fit.script.test.ts reads him, judged by the rulebook (rulebook.ts ruleJudge), written to ruleKey.data.ts, and
// compared with the arch14 key (tools/archrules/arch14key.json, the arch15 judged.data.ts) and the arch17 key (judged.data.ts
// now). ARCH_RULEKEY_OUT=file: the report. ARCH_RULEKEY_DRY=1: report only.
import { readFileSync, writeFileSync } from "node:fs";
import { test } from "vitest";
import { familyOf } from "./families.ts";
import { judgedPlayers } from "./fit.script.test.ts";
import { mergedId } from "./merges.data.ts";
import { ARCHETYPES } from "./classify.ts";
import { ruleJudge } from "./rulebook.ts";

const BY_ID = new Map(ARCHETYPES.map((a) => [a.id, a]));
const famOf = (id) => {
	const a = BY_ID.get(mergedId(id));
	return a ? familyOf(a) : undefined;
};

export const agreement = (rows, keyA, keyB) => {
	let n = 0,
		share = 0,
		firstIn = 0,
		firstEq = 0,
		famFirst = 0;
	for (const r of rows) {
		const a = keyA(r)?.map(mergedId);
		const b = keyB(r)?.map(mergedId);
		if (!a?.length || !b?.length) continue;
		n++;
		if (a.some((x) => b.includes(x))) share++;
		if (b.includes(a[0])) firstIn++;
		if (a[0] === b[0]) firstEq++;
		if (famOf(a[0]) === famOf(b[0])) famFirst++;
	}
	const p = (x) => `${((100 * x) / n).toFixed(1)}%`;
	return `n ${n}: share a build ${p(share)}, first pick among the other's ${p(firstIn)}, same first pick ${p(firstEq)}, same family of first pick ${p(famFirst)}`;
};

test.skipIf(!process.env.RUN_ARCHETYPE_RULEKEY)(
	"rule answer key",
	() => {
		const k14 = JSON.parse(
			readFileSync("tools/archrules/arch14key.json", "utf8"),
		);
		const players = judgedPlayers();
		if (process.env.ARCH_RULEKEY_QUANTILES) {
			const q = {};
			for (const c of Object.keys(players[0].cv)) {
				const v = players.map((p) => p.cv[c]).sort((a, b) => a - b);
				q[c] = Array.from(
					{ length: 21 },
					(_, i) =>
						Math.round(
							100 * v[Math.min(v.length - 1, Math.floor((i / 20) * v.length))],
						) / 100,
				);
			}
			writeFileSync(
				"src/common/archetypes/ruleQuantiles.data.ts",
				`// archrules: where a blended class value (score.ts classValues) stands among players: per class, the 0th, 5th, ..., 100th
// percentile over the judged population (549 players: real NBA 1992-2025, a random league, draft prospects and a simulated
// league; judged.data.ts, judgedSim.data.ts). The rulebook's "top X%" bars are read through it. GENERATED by
// ruleKey.script.test.ts (RUN_ARCHETYPE_RULEKEY=1 ARCH_RULEKEY_QUANTILES=1).
export const CV_QUANTILES: Record<string, number[]> = ${JSON.stringify(q)};
`,
			);
			return;
		}
		const rows = players.map((p) => {
			const builds = p.rows.map((r) => r.a);
			const v = ruleJudge(builds, { cv: p.cv, style: p.style });
			return { p, rule: v.ids, qualified: v.qualified };
		});
		const real = rows.filter((r) => k14[r.p.j.key]);
		const test = rows.filter((r) => r.p.j.split === "test");
		const famCount = {};
		for (const r of rows) {
			const f = famOf(r.rule[0]);
			famCount[f] = (famCount[f] ?? 0) + 1;
		}
		const nAcc = [0, 0, 0, 0];
		for (const r of rows) nAcc[r.rule.length]++;
		const out = [
			`rule key: ${rows.length} players, ${rows.filter((r) => r.qualified).length} with a qualifying build (the rest: nearest specific build); builds accepted 1/2/3: ${nAcc[1]}/${nAcc[2]}/${nAcc[3]}`,
			`first-pick families: ${Object.entries(famCount)
				.sort((a, b) => b[1] - a[1])
				.map(([f, c]) => `${f} ${c}`)
				.join(", ")}`,
			`first-pick builds used: ${new Set(rows.map((r) => r.rule[0])).size}`,
			`rule vs arch17 (all 549): ${agreement(
				rows,
				(r) => r.rule,
				(r) => r.p.j.ids,
			)}`,
			`rule vs arch17 (test split): ${agreement(
				test,
				(r) => r.rule,
				(r) => r.p.j.ids,
			)}`,
			`rule vs arch14 (400 shared): ${agreement(
				real,
				(r) => r.rule,
				(r) => k14[r.p.j.key],
			)}`,
			`arch17 vs arch14 (400 shared, reference): ${agreement(
				real,
				(r) => r.p.j.ids,
				(r) => k14[r.p.j.key],
			)}`,
			`rule vs arch17 by population: ${[...new Set(rows.map((r) => r.p.pop))]
				.map(
					(pop) =>
						`${pop}: ${agreement(
							rows.filter((r) => r.p.pop === pop),
							(r) => r.rule,
							(r) => r.p.j.ids,
						)}`,
				)
				.join("; ")}`,
			"",
			"player | rule key | arch17 | arch14",
			...rows.map(
				(r) =>
					`${r.p.j.key} (${r.p.pos}, ${r.p.j.split}${r.qualified ? "" : ", nearest"}) | ${r.rule.join(", ")} | ${r.p.j.ids.join(", ")} | ${(k14[r.p.j.key] ?? []).join(", ")}`,
			),
		];
		writeFileSync(
			process.env.ARCH_RULEKEY_OUT ?? "/tmp/claude-0/arch-rulekey.txt",
			out.join("\n") + "\n",
		);
		if (!process.env.ARCH_RULEKEY_DRY) {
			const key = Object.fromEntries(rows.map((r) => [r.p.j.key, r.rule]));
			writeFileSync(
				"src/common/archetypes/ruleKey.data.ts",
				`// archrules: the rule answer key. For every judged player (judged.data.ts and judgedSim.data.ts, by key) the 1-3 builds the
// judging rulebook accepts (rulebook.ts ruleJudge, rulebook.data.ts), best first. GENERATED by ruleKey.script.test.ts
// (RUN_ARCHETYPE_RULEKEY=1); fit.script.test.ts fits against it with ARCH_KEY=rule. Splits are the judged sets' own.
export const RULE_KEY: Record<string, string[]> = ${JSON.stringify(key)};
`,
			);
		}
	},
	1800000,
);
