// The archetype table. Each archetype is a weighted profile over normalized rating dimensions (see composites.ts), a
// height gate and optional signature-skill requirements, not a rule. `w` is -3..+3: how far above (+) or below (-)
// typical-for-his-size the archetype wants that dimension (3 = elite). Dimensions not listed are expected to be
// ordinary, so a player with an elite skill the profile does not mention matches it less.

import type {
	ArchetypeDef,
	ArchetypeFamily,
	ArchetypeGroup,
	DimKey,
	Pos,
	SkillLabel,
} from "./types.ts";

type Opts = {
	req?: SkillLabel[];
	bonus?: SkillLabel[];
	rare?: true;
	need?: Partial<Record<DimKey, number>>;
	needFor?: Partial<Record<DimKey, number>>;
	level?: [number, number];
	age?: [number, number];
	// Position prior overrides (see position.ts)
	pos?: Partial<Record<Pos, number | null>>;
	tags?: string[];
};

const make =
	(group: ArchetypeGroup) =>
	(
		name: string,
		family: ArchetypeFamily,
		hgt: [number, number],
		w: Partial<Record<DimKey, number>>,
		desc: string,
		opts: Opts = {},
	): ArchetypeDef => ({
		id: name
			.toLowerCase()
			.replace(/&/g, "and")
			.replace(/[^\da-z]+/g, "-")
			.replace(/^-|-$/g, ""),
		name,
		group,
		family,
		desc,
		w,
		hgt,
		req: opts.req,
		bonus: opts.bonus,
		rare: opts.rare,
		need: opts.need,
		needFor: opts.needFor,
		level: opts.level,
		age: opts.age,
		pos: opts.pos,
		tags: [group, family, ...(opts.tags ?? [])],
	});

